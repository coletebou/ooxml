"""Writes src/core/text/html-named-references.generated.ts from the HTML Standard's list of named
character references (https://html.spec.whatwg.org/entities.json, saved to a file first; see
PROVENANCE.md).

    python scripts/make-html-named-references.py <path of entities.json>
"""
import io
import json
import os
import sys

source = json.load(io.open(sys.argv[1], encoding='utf-8'))
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = os.path.join(root, 'src', 'core', 'text', 'html-named-references.generated.ts')

names = {key[1:-1]: entry['codepoints'] for key, entry in source.items() if key.endswith(';')}
bare = {key[1:] for key in source if not key.endswith(';')}
# A name a reader also takes without its semicolon stands for the same text as with it.
assert all(source['&' + name]['codepoints'] == names[name] for name in bare)

entries = [
    '%s%s:%s' % (name, '*' if name in bare else '', '.'.join('%x' % code for code in names[name]))
    for name in sorted(names)
]
rows = ['']
for entry in entries:
    if rows[-1] and len(rows[-1]) + 1 + len(entry) > 100:
        rows.append(entry)
    else:
        rows[-1] = '%s %s' % (rows[-1], entry) if rows[-1] else entry

lines = [
    '/**',
    ' * The named character references of the HTML Standard (entities.json, listed at',
    ' * https://html.spec.whatwg.org/multipage/named-characters.html), Copyright (c) WHATWG (Apple,',
    ' * Google, Mozilla, Microsoft), under the BSD 3-Clause License (see PROVENANCE.md).',
    ' * GENERATED by `scripts/make-html-named-references.py`: do not edit by hand.',
    ' */',
    '',
    '/**',
    ' * `name:code[.code]` for each `&name;`, its code points in hex, sorted by name, white space',
    ' * between; a `*` after a name marks one a reader also takes without its semicolon (`&eacute`).',
    ' */',
    'export const NAMED_REFERENCES = `',
] + rows + ['`;']
io.open(target, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', target, len(entries), 'names,', len(bare), 'also without a semicolon')
